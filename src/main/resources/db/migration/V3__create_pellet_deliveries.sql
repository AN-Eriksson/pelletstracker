-- Pellets added to the user's stock (deliveries, or the stock on hand when starting to track).
-- Several deliveries on the same day are allowed, unlike consumption entries.

CREATE TABLE pellet_deliveries (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_date DATE    NOT NULL,
    amount_kg     INTEGER NOT NULL,
    user_id       BIGINT  NOT NULL REFERENCES app_users (id),
    CONSTRAINT ck_pellet_deliveries_amount_kg CHECK (amount_kg >= 1)
);

CREATE INDEX ix_pellet_deliveries_user_date ON pellet_deliveries (user_id, delivery_date);

-- Login with GitHub: users created by a GitHub login have no password, and each user can be linked to
-- external accounts (user_identities).

ALTER TABLE app_users ALTER COLUMN password_hash DROP NOT NULL;

-- Current GitHub username, shown in the app (updated on every GitHub login; not unique)
ALTER TABLE app_users ADD COLUMN display_name VARCHAR(100);

-- For the cap on new accounts per day. Existing users get the time of this migration
ALTER TABLE app_users ADD COLUMN created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now();

-- An external account linked to a user. subject is the provider's fixed id (GitHub's numeric user id),
-- not the username, which can change and be taken by someone else
CREATE TABLE user_identities (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id  BIGINT       NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    provider VARCHAR(50)  NOT NULL,
    subject  VARCHAR(255) NOT NULL,
    CONSTRAINT uk_user_identities_provider_subject UNIQUE (provider, subject)
);

CREATE INDEX ix_user_identities_user_id ON user_identities (user_id);
